// 6. Power and Square Root
// Use Math.pow() to calculate 2 raised to the power 3 and Math.sqrt() to find the square root of 64.
// Example:
// Math.pow(2, 3) → 8
// Math.sqrt(64) → 8

//solution-->

let num1 = 2;
let num2 = 64;

console.log(`Power of ${num1} :`, Math.pow(num1 , 3)); // 8
console.log(`square root of ${num2} :`, Math.sqrt(num2)); // 8